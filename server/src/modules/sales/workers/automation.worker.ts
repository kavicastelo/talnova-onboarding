import mongoose from "mongoose";
import { Job } from "../../../infrastructure/queue/queue.service.js";
import SalesTask, { ISalesTask } from "../models/task.model.js";
import Lead from "../models/lead.model.js";
import Deal from "../models/deal.model.js";
import SystemLogBuffer from "../../../infrastructure/telemetry/system-log-buffer.js";
import { AuditLog } from "../../audit-logs/models/audit-log.model.js";

export interface AutomationJobData {
  ruleId:
    | "auto_followup"
    | "stale_lead_escalation"
    | "stale_deal_warning"
    | "round_robin_assignment"
    | string;
  triggerType:
    | "lead_created"
    | "lead_status_changed"
    | "deal_stage_changed"
    | "comm_inbound_received"
    | "stale_lead_check"
    | "stale_deal_check"
    | string;
  targetId: string;
  action:
    | "create_task"
    | "assign_owner"
    | "escalate_priority"
    | "flag_deal_risk"
    | "custom";
  actionPayload?: Record<string, any>;
  organizationId?: string;
  idempotencyKey?: string;
}

export async function processAutomationJob(job: Job<AutomationJobData>): Promise<void> {
  const { ruleId, triggerType, targetId, action, actionPayload, organizationId, idempotencyKey } =
    job.data;

  const orgId = organizationId || job.options.organizationId?.toString();
  const effectiveIdempotencyKey = idempotencyKey || job.options.idempotencyKey || `${ruleId}:${targetId}`;

  try {
    if (action === "create_task") {
      const taskTag = `[AUTOMATION:${effectiveIdempotencyKey}]`;

      // Check task-level duplicate suppression
      const existingTask = await SalesTask.findOne({
        leadId: actionPayload?.leadId || (mongoose.Types.ObjectId.isValid(targetId) ? new mongoose.Types.ObjectId(targetId) : undefined),
        outcomeNotes: { $regex: escapeRegex(taskTag) },
      });

      if (!existingTask) {
        const dueDate = actionPayload?.dueDate
          ? new Date(actionPayload.dueDate)
          : new Date(Date.now() + (actionPayload?.dueInHours ?? 24) * 3600 * 1000);

        const task = new SalesTask({
          title: actionPayload?.title || `Automated Follow-up: ${triggerType}`,
          description: actionPayload?.description || `Auto-generated by workflow rule ${ruleId}`,
          type: actionPayload?.type || "follow_up",
          priority: actionPayload?.priority || "high",
          dueDate,
          leadId: actionPayload?.leadId || (mongoose.Types.ObjectId.isValid(targetId) ? new mongoose.Types.ObjectId(targetId) : undefined),
          dealId: actionPayload?.dealId,
          contactId: actionPayload?.contactId,
          companyId: actionPayload?.companyId,
          assignedTo: actionPayload?.assignedTo,
          outcomeNotes: `${taskTag} Generated by automation rule: ${ruleId}`,
        });

        await task.save();
      }
    } else if (action === "assign_owner" && actionPayload?.ownerId) {
      if (mongoose.Types.ObjectId.isValid(targetId)) {
        await Lead.findByIdAndUpdate(targetId, {
          assignedOwnerId: new mongoose.Types.ObjectId(actionPayload.ownerId),
        });
      }
    } else if (action === "escalate_priority") {
      if (mongoose.Types.ObjectId.isValid(targetId)) {
        await Lead.findByIdAndUpdate(targetId, {
          priority: "high",
        });

        const taskTag = `[AUTOMATION:${effectiveIdempotencyKey}]`;
        const existingTask = await SalesTask.findOne({
          leadId: new mongoose.Types.ObjectId(targetId),
          outcomeNotes: { $regex: escapeRegex(taskTag) },
        });

        if (!existingTask) {
          const task = new SalesTask({
            title: actionPayload?.title || "Urgent: Stale Lead Follow-Up Required",
            description: actionPayload?.description || "Lead has been inactive for > 7 days.",
            type: "call",
            priority: "urgent",
            dueDate: new Date(Date.now() + 12 * 3600 * 1000), // Due in 12 hours
            leadId: new mongoose.Types.ObjectId(targetId),
            assignedTo: actionPayload?.assignedTo,
            outcomeNotes: `${taskTag} Escalated stale lead status`,
          });
          await task.save();
        }
      }
    } else if (action === "flag_deal_risk") {
      if (mongoose.Types.ObjectId.isValid(targetId)) {
        const nextActionNote = actionPayload?.nextAction || "Urgent: Stale deal review required";
        await Deal.findByIdAndUpdate(targetId, {
          nextAction: nextActionNote,
        });

        const taskTag = `[AUTOMATION:${effectiveIdempotencyKey}]`;
        const existingTask = await SalesTask.findOne({
          dealId: new mongoose.Types.ObjectId(targetId),
          outcomeNotes: { $regex: escapeRegex(taskTag) },
        });

        if (!existingTask) {
          const task = new SalesTask({
            title: actionPayload?.title || "Stale Deal Warning: Pipeline Review",
            description: actionPayload?.description || "Deal in negotiation/proposal stage has had no movement for > 14 days.",
            type: "meeting",
            priority: "high",
            dueDate: new Date(Date.now() + 24 * 3600 * 1000),
            dealId: new mongoose.Types.ObjectId(targetId),
            assignedTo: actionPayload?.assignedTo,
            outcomeNotes: `${taskTag} Stale deal flagged`,
          });
          await task.save();
        }
      }
    }

    // Telemetry and Audit Logging
    SystemLogBuffer.record({
      level: "info",
      source: "sales:automation:worker",
      eventType: "AUTOMATION_EXECUTED",
      description: `Rule ${ruleId} executed action ${action} on target ${targetId}`,
      organizationId: orgId,
      metadata: { ruleId, triggerType, targetId, action, idempotencyKey: effectiveIdempotencyKey },
    });

    if (orgId && mongoose.Types.ObjectId.isValid(orgId)) {
      await AuditLog.create({
        organizationId: new mongoose.Types.ObjectId(orgId),
        actorType: "system",
        eventCategory: "sales",
        eventType: "SALES_AUTOMATION_EXECUTED",
        resourceType: "sales_automation",
        resourceId: mongoose.Types.ObjectId.isValid(targetId) ? new mongoose.Types.ObjectId(targetId) : undefined,
        action: "execute",
        description: `Automation rule ${ruleId} performed ${action} on ${targetId}`,
        metadata: {
          ruleId,
          triggerType,
          action,
          idempotencyKey: effectiveIdempotencyKey,
        },
        severity: "info",
      }).catch(() => {});
    }
  } catch (error: any) {
    SystemLogBuffer.record({
      level: "warning",
      source: "sales:automation:worker",
      eventType: "AUTOMATION_ERROR",
      description: `Failed to execute rule ${ruleId} action ${action} for target ${targetId}: ${error.message}`,
      organizationId: orgId,
    });
    throw error;
  }
}

function escapeRegex(text: string): string {
  return text.replace(/[-[\]{}()*+?.,\\^$|#\s]/g, "\\$&");
}

export default processAutomationJob;
